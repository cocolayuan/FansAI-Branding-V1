const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror', e => errors.push(e.message));
  const url=process.env.TEST_URL || pathToFileURL(path.resolve(__dirname,'../index.html')).href;
  await page.goto(url);
  await page.waitForFunction(() => window.FansAICharts && window.FansAIFilters);
  assert.equal((await page.evaluate(()=>FansAICharts.getSummary())).profit,3159.11);
  await page.locator('#dayPicker [data-date="2026-10-27"]').click();
  assert.ok((await page.evaluate(()=>FansAICharts.getSummary())).profit<0);
  assert.equal(await page.locator('#returnStatus').textContent(),'未回本');
  assert.equal(await page.locator('#costColumn .column-cap').evaluate(el=>parseFloat(el.style.height)>0),true);
  await page.locator('[data-metric="profit"]').click();
  assert.ok(await page.locator('#roiChart rect[fill="#e38730"]').count());
  await page.locator('#resetDay').click();
  await page.locator('[data-metric="roi"]').click();
  const first=page.locator('#roiChart [data-day="2026-10-23"]');
  await first.focus();await page.keyboard.press('ArrowRight');
  assert.equal((await page.evaluate(()=>FansAICharts.getState())).selected,'2026-10-24');
  await page.keyboard.press('ArrowRight');
  assert.equal((await page.evaluate(()=>FansAICharts.getState())).selected,'2026-10-25');
  await page.locator('#resetDay').click();
  await page.locator('#autoButton').click();
  await page.waitForTimeout(5150);
  assert.equal((await page.evaluate(()=>FansAICharts.getState())).selected,'2026-10-23');
  await page.locator('#dayPicker [data-date="2026-10-24"]').click();
  assert.equal((await page.evaluate(()=>FansAICharts.getState())).autoplay,false);
  await page.locator('#openFilters').click();
  await page.locator('[data-filter-period="today"]').click();
  await page.locator('.filter-channels > summary').click();
  await page.locator('[data-filter-channel="tiktok"]').click();
  await page.locator('.filter-apply').click();
  assert.equal((await page.evaluate(()=>FansAICharts.getState())).channel,'tiktok');
  assert.equal((await page.evaluate(()=>FansAICharts.getSummary())).roi,null);
  assert.equal(await page.locator('#roiValue').textContent(),'—');
  assert.equal(await page.locator('#cpiValue').textContent(),'—');
  await page.locator('#openFilters').click();
  await page.locator('.filter-reset').click();
  await page.locator('.filter-date-details > summary').click();
  await page.locator('#filterStart').click();
  assert.equal(await page.locator('#filterCalendar').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(255, 255, 255)');
  assert.equal(await page.locator('#filterCalendar [data-date="2026-10-22"]').isDisabled(),true);
  await page.locator('#filterCalendar [data-date="2026-10-25"]').click();
  await page.locator('#filterEnd').click();
  await page.locator('#filterCalendar [data-date="2026-10-27"]').click();
  await page.locator('.filter-apply').click();
  assert.equal((await page.evaluate(()=>FansAICharts.getState())).start,'2026-10-25');
  assert.equal((await page.evaluate(()=>FansAICharts.getState())).end,'2026-10-27');
  assert.equal(await page.locator('#dayPicker button').count(),3);
  await page.locator('#openFilters').click();
  await page.locator('[data-filter-period="today"]').click();
  await page.locator('[data-filter-cancel]').click();
  assert.equal((await page.evaluate(()=>FansAICharts.getState())).period,'custom');
  await page.locator('#openFilters').click();
  await page.locator('.filter-reset').click();
  await page.locator('.filter-apply').click();
  await page.locator('[data-legend="apple"]').click();
  assert.equal(await page.locator('[data-legend="apple"]').getAttribute('aria-pressed'),'false');
  assert.equal((await page.evaluate(()=>FansAICharts.getSummary())).profit,3159.11);
  await page.locator('#themeButton').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.reload();await page.waitForFunction(()=>window.FansAICharts);
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  for(const width of [768,390,320]){
    await page.setViewportSize({width,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`overflow at ${width}`);
    assert.ok(await page.locator('#profitValue').evaluate(e=>e.scrollWidth<=e.clientWidth),`profit overflow at ${width}`);
  }
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.locator('#replayButton').click();
  assert.equal(await page.locator('#profitValue').textContent(),'+$3,159.11');
  await page.locator('#autoButton').click();
  assert.equal((await page.evaluate(()=>FansAICharts.getState())).autoplay,false);
  assert.equal((await page.evaluate(()=>FansAICharts.getState())).selected,'2026-10-23');
  assert.deepEqual(errors,[]);
  const touch=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await touch.goto(url);await touch.waitForFunction(()=>window.FansAICharts);
  await touch.locator('#roiChart').scrollIntoViewIfNeeded();
  const box=await touch.locator('#roiChart').boundingBox();
  const session=await touch.context().newCDPSession(touch);
  await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:box.x+box.width*.15,y:box.y+box.height*.5}]});
  for(const fraction of [.3,.5,.7,.96]){
    await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:box.x+box.width*fraction,y:box.y+box.height*.5}]});
  }
  await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.equal((await touch.evaluate(()=>FansAICharts.getState())).selected,'2026-10-29');
  await touch.close();
  console.log('PASS Offline load, aggregate math, loss state, ROI/profit switching, keyboard dates, touch scrubbing, 5-second playback, filters, white calendar, cancel/reset, legend, theme persistence, 320/390/768 layout, reduced motion; no runtime errors.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
